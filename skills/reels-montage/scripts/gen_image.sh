#!/bin/bash
# Генерация картинки для вставки Ф4 через Codex CLI (нужна подписка ChatGPT и установленный `codex`, без API-ключа).
#   gen_image.sh insert  "<что на картинке>" /abs/out.png   — вставка на весь кадр, вертикаль 9:16, фото/кино
#   gen_image.sh kontorka "<сцена>" /abs/out.png    — тренд «Конторка»: кривой 3D катсцен 2000-х
#   gen_image.sh sticker "<персонаж/объект>" /abs/out.png   — стикер: прозрачный фон, объект целиком, без тени/подложки
# ~2 мин и ~25k токенов Codex на картинку. Текст на картинке не просим (текст — наш, Montserrat, поверх).
set -e
KIND="$1"; WHAT="$2"; OUT="$3"
[ -z "$OUT" ] && { echo "usage: gen_image.sh insert|sticker \"prompt\" /abs/out.png"; exit 1; }
DIR="$(dirname "$OUT")"; NAME="$(basename "$OUT")"; mkdir -p "$DIR"
KONTORKA="Стиль изображения: нарочито кривой 3D-рендер в духе катсцен видеоигр начала 2000-х — как в трендах «Конторка» и «Зазеркалье». Плоский невыразительный свет, деревянная скованная мимика, тяжёлые заскриптованные позы, статичный ракурс камеры, приглушённая мутноватая цветокоррекция. Специально НЕ фотореализм, НЕ гладкий современный CGI — угловатая, чуть отталкивающая графика «забытой игры со старого диска». Шарж: гротескная преувеличенная мимика и позы, абсурдная комичная ситуация — кадр должен быть смешным."
if [ "$KIND" = kontorka ]; then   # тренд «Конторка» : вся история из таких кадров
  SPEC="Вертикальный кадр 9:16 для рилса: $WHAT. $KONTORKA"
elif [ "$KIND" = sticker ]; then
  SPEC="Стикер для вертикального видео: $WHAT. Объект целиком, по центру, ПРОЗРАЧНЫЙ фон (PNG с альфа-каналом), без тени, без подложки, без рамки."
else
  SPEC="Вертикальный кадр 9:16 для вставки в рилс: $WHAT. Кинематографичный свет, высокая детализация."
fi
cd "$DIR" && codex exec --skip-git-repo-check -C "$DIR" -s workspace-write \
  "Сгенерируй картинку встроенным инструментом генерации изображений. $SPEC Никакого текста, букв и логотипов на изображении. Сохрани результат файлом $NAME в текущей папке. Ответь только путём к файлу." >/dev/null 2>&1
[ -s "$OUT" ] && echo "$OUT" || { echo "ОШИБКА: файл не создан"; exit 1; }
