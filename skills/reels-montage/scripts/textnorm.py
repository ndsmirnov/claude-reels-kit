"""Стандарт экранного текста рилсов (по умолчанию; поменяй под свой вкус). Применяется ко ВСЕМУ тексту на кадре:
субтитры, заголовки, тезисы, призыв, карточки (subs.py и remotion/render.sh).
  • буква «ё» не используется → «е»;
  • деньги: 12,000 ₽ — разделитель тысяч запятая, знак рубля через пробел
    («12000 рублей», «12 000 руб.», «12 тыс.», «12 тысяч рублей», «12к» → «12,000 ₽»).
Числа без денежного контекста (годы, проценты, «137 агентов») не трогаем, кроме разделителя тысяч у ≥ 10 000.
"""
import re

_RUB = r"(?:₽|руб(?:лей|ля|ль)?\.?|р\.)"
_THOUS = r"(?:тыс(?:яч[аи]?)?\.?|к\b|k\b)"


def _fmt(n):
    return f"{n:,}"


def _num(s):
    return int(re.sub(r"[\s ,]", "", s))


def norm(text):
    if not text:
        return text
    t = text.replace("ё", "е").replace("Ё", "Е")
    # «12 тыс. рублей» → «12,000 ₽»; «12 тыс.»/«12к» без рубля → «12,000» (может быть «12 тыс. подписчиков» —
    # если это деньги, ₽ дописывает автор текста: «12 тыс. ₽» / «12к рублей»)
    t = re.sub(rf"(\d+(?:[.,]\d+)?)\s*{_THOUS}(\s*{_RUB})?",
               lambda m: _fmt(int(round(float(m.group(1).replace(",", ".")) * 1000))) + (" ₽" if m.group(2) else ""), t)
    # «12000 рублей» / «12 000 руб.» / «12,000₽» → 12,000 ₽
    t = re.sub(rf"(\d{{1,3}}(?:[\s ,]\d{{3}})+|\d+)\s*{_RUB}", lambda m: _fmt(_num(m.group(1))) + " ₽", t)
    # голые большие числа «12000» / «12 000» → «12,000» (годы 4-значные не трогаем)
    t = re.sub(r"(?<![\d,])(\d{1,3}(?:[\s ]\d{3})+|\d{5,})(?![\d,])", lambda m: _fmt(_num(m.group(1))), t)
    t = t.replace("₽ ₽", "₽")
    return t


if __name__ == "__main__":
    for s in ["Монтажёр берёт 12 тыс. ₽ за выпуск", "12 тыс. подписчиков", "12000 рублей", "12 000 руб.", "а я плачу 2500₽", "12к в месяц",
              "137 агентов", "в 2026 году", "150000 подписчиков", "1,5 тыс. рублей", "Ёлка"]:
        print(f"{s!r:40} → {norm(s)!r}")
